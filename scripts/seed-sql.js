#!/usr/bin/env node
/*
 * Generates supabase/seed.sql from js/data.js (stores from branches[], menu_items from catalog()).
 *   node scripts/seed-sql.js > supabase/seed.sql
 * Never edit seed.sql by hand: change js/data.js and regenerate, so the site, the assistant and the DB agree.
 */
"use strict";
const K = require("../js/data.js");

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const out = [];
out.push("-- Generated by scripts/seed-sql.js from js/data.js. Do not edit by hand.", "begin;", "");

out.push("insert into public.stores (id, name, city, whatsapp, address, open_time, close_time, sort) values");
out.push(K.branches.map((b, i) => `  (${q(b.id)}, ${q(b.name)}, ${q(b.city)}, ${q(b.whatsapp)}, ${q(b.address)}, ${q(b.open)}, ${q(b.close)}, ${i})`).join(",\n"));
out.push("on conflict (id) do update set name = excluded.name, city = excluded.city, whatsapp = excluded.whatsapp, address = excluded.address,");
out.push("  open_time = excluded.open_time, close_time = excluded.close_time, sort = excluded.sort;", "");

const items = Object.values(K.catalog());
out.push("insert into public.menu_items (id, name, kind, category, size, description, price, veg, active, sort) values");
out.push(items.map((it) => `  (${q(it.id)}, ${q(it.name)}, ${q(it.kind)}, ${q(it.cat)}, ${q(it.size || null)}, ${q(it.desc)}, ${it.price}, ${it.veg}, true, ${it.sort})`).join(",\n"));
out.push("on conflict (id) do update set name = excluded.name, kind = excluded.kind, category = excluded.category, size = excluded.size,");
out.push("  description = excluded.description, price = excluded.price, veg = excluded.veg, sort = excluded.sort;", "");

out.push("commit;", "");
out.push("-- First owner: create the user in Supabase → Authentication → Users (email + password), then run:");
out.push("--   insert into public.staff (user_id, full_name, email, role)");
out.push("--   select id, 'Nombre del dueño', email, 'owner' from auth.users where email = 'dueno@ejemplo.com';");
out.push("-- Everyone else is created from /admin → Equipo.");
process.stdout.write(out.join("\n") + "\n");
